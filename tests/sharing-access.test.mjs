import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
process.env.DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'share-access-'));
process.env.TELEGRAM_BOT_TOKEN = '';
const { db } = await import('../src/lib/server/db.js');
const files = await import('../src/lib/server/files.js');
const shares = await import('../src/lib/server/shares.js');
const makeUser = (name) => Number(db.prepare('INSERT INTO users(tg_id,first_name,created_at) VALUES (?,?,?)').run(name,name,new Date().toISOString()).lastInsertRowid);
const owner = makeUser('owner'), guest = makeUser('guest'), stranger = makeUser('stranger');
const root = files.createFolder(owner,null,'root');
const child = files.createFolder(owner,root.id,'nested');
const outside = files.createFolder(owner,null,'outside');
const insert = (parent, name) => { const id=files.newId(), now=new Date().toISOString(); db.prepare("INSERT INTO files(id,user_id,parent_id,name,kind,size,storage,created_at,updated_at) VALUES (?,?,?,?,'file',0,'local',?,?)").run(id,owner,parent,name,now,now); return id; };
const nested = insert(child.id,'inside'), other = insert(outside.id,'outside');
test('approval protects both folder and descendants, and is per user', () => {
 const link = shares.createShare(owner,root.id,{mode:'approval'});
 assert.equal(shares.shareAccess(link.token,null).status,'signin');
 assert.equal(shares.resolveShare(link.token,guest,nested),null);
 assert.equal(shares.requestShare(link.token,guest),true);
 assert.equal(shares.shareAccess(link.token,guest).status,'pending');
 assert.equal(shares.decideRequest(stranger,link.id,guest,'approved'),false);
 assert.equal(shares.decideRequest(owner,link.id,guest,'approved'),true);
 assert.equal(shares.resolveShare(link.token,guest,nested).id,nested);
 assert.equal(shares.resolveShare(link.token,stranger,nested),null);
 assert.equal(shares.resolveShare(link.token,guest,other),null);
 assert.equal(shares.sharedChildren(link.token,guest,root.id)[0].id,child.id);
 shares.decideRequest(owner,link.id,guest,'denied');
 assert.equal(shares.resolveShare(link.token,guest,nested),null);
 shares.requestShare(link.token,guest);
 assert.equal(shares.shareAccess(link.token,guest).status,'pending');
 shares.revokeShare(owner,link.id);
 assert.equal(shares.shareAccess(link.token,guest).status,'missing');
});
test('public folder links and deleted ancestors', () => {
 const link = shares.createShare(owner,root.id);
 assert.equal(shares.resolveShare(link.token,null,nested).id,nested);
 assert.equal(shares.resolveShare(link.token,null,other),null);
 files.trashFile(owner,child.id);
 assert.equal(shares.resolveShare(link.token,null,nested),null);
 files.restoreFile(owner,child.id);
 shares.revokeShare(owner,link.id);
});
test('file links do not grant access to another file', () => {
 const link = shares.createShare(owner,nested);
 assert.equal(shares.resolveShare(link.token).id,nested);
 assert.equal(shares.resolveShare(link.token,null,other),null);
});
